#!/usr/bin/env node
"use strict";

/**
 * Renders the machine-surface capability reference from the operation registry,
 * so the agent skills documentation can never drift from the implementation.
 *
 * Usage:
 *   node scripts/generate-app-operations-docs.js            # write the file
 *   node scripts/generate-app-operations-docs.js --check     # exit 1 if stale
 */

const fs = require("fs");
const path = require("path");
const { createRegistry } = require("../src/helpers/appOperations/registry");
const { coreOperations } = require("../src/helpers/appOperations/coreOperations");
const { actionOperations } = require("../src/helpers/appOperations/actionOperations");
const { domainOperations } = require("../src/helpers/appOperations/domainOperations");
const { jobOperations } = require("../src/helpers/appOperations/jobOperations");

const REFERENCES_DIR = path.join(__dirname, "..", "agent-skills", "superting-api", "references");
const OUTPUT_PATH = path.join(REFERENCES_DIR, "operations.md");
const ROUTES_PATH = path.join(REFERENCES_DIR, "routes.md");

function listOperations() {
  return createRegistry([
    ...coreOperations(),
    ...actionOperations(),
    ...domainOperations(),
    ...jobOperations(),
  ]).list();
}

function renderParamTable(operation) {
  const entries = Object.entries(operation.params);
  if (entries.length === 0) return "_No parameters._\n";
  const lines = ["| 参数 | 类型 | 必填 | 说明 |", "| --- | --- | --- | --- |"];
  for (const [name, spec] of entries) {
    const type =
      spec.type === "array"
        ? `array<${spec.items}>`
        : spec.enum
          ? spec.enum.join("\\|")
          : spec.type;
    lines.push(
      `| \`${name}\` | ${type} | ${spec.required ? "是" : "否"} | ${spec.description ?? ""} |`
    );
  }
  return lines.join("\n") + "\n";
}

function renderOperationsDoc(operations) {
  const byCategory = new Map();
  for (const operation of operations) {
    const category = operation.id.split(".")[0];
    if (!byCategory.has(category)) byCategory.set(category, []);
    byCategory.get(category).push(operation);
  }

  const lines = [
    "<!-- Generated by scripts/generate-app-operations-docs.js — do not edit by hand. -->",
    "",
    "# 全部机器能力（MCP 工具与 CLI 路由）",
    "",
    `共 ${operations.length} 项能力。每一行都由主进程的操作注册表`,
    "（`src/helpers/appOperations/`）生成：同一份定义同时投影为 MCP 工具与",
    "CLI 路由，因此两边的能力集合不再可能不一致。",
    "",
    "策略含义：`read` 只读；`write` 可写；`destructive` 需显式确认",
    "（CLI 需 `--yes`，MCP 客户端按 `destructiveHint` 确认）；",
    "`needs UI` 表示该能力需要 SuperTing 窗口在前台运行（通过主↔渲染桥执行）。",
    "",
  ];

  for (const [category, ops] of [...byCategory.entries()].sort()) {
    lines.push(`## ${category}`, "");
    for (const operation of ops) {
      const policy =
        operation.policy === "read"
          ? "read"
          : `${operation.policy}${operation.rendererRequired ? " · needs UI" : ""}`;
      lines.push(`### \`${operation.id}\` — ${operation.title}`, "");
      lines.push(operation.description, "");
      lines.push(`- 策略：\`${policy}\``);
      if (operation.mcp) lines.push(`- MCP 工具：\`${operation.mcp.name}\``);
      if (operation.cli) {
        const command = operation.cli.command
          ? `（CLI：\`superting ${operation.cli.command}\`）`
          : "";
        lines.push(`- CLI 路由：\`${operation.cli.method} ${operation.cli.path}\`${command}`);
      }
      lines.push("");
      if ((operation.notes ?? []).length > 0) {
        lines.push("说明：", "");
        for (const note of operation.notes) lines.push(`- ${note}`);
        lines.push("");
      }
      lines.push(renderParamTable(operation));
    }
  }

  return lines.join("\n");
}

/** HTTP reference for the loopback bridge, generated from the same registry. */
function renderRoutesDoc(operations) {
  const routes = operations.filter((operation) => operation.cli);
  const byFamily = new Map();
  for (const operation of routes) {
    const family = operation.id.split(".")[0];
    if (!byFamily.has(family)) byFamily.set(family, []);
    byFamily.get(family).push(operation);
  }

  const lines = [
    "<!-- Generated by scripts/generate-app-operations-docs.js — do not edit by hand. -->",
    "",
    "# 全路由参考（请求体与语义）",
    "",
    `共 ${routes.length} 条路由，由主进程操作注册表（\`src/helpers/appOperations/\`）生成；`,
    "每条路由与同名 MCP 工具共享一份实现。变更类路由会向应用窗口广播事件，界面实时刷新（无需重载）。",
    "",
    "认证：回环地址 + `Authorization: Bearer <token>`（token 见 `~/.superting/cli-bridge.json`）。",
    "参数位置见「位置」列：path=路径占位符，query=查询串，body=JSON 请求体。",
    "",
  ];

  for (const [family, ops] of [...byFamily.entries()].sort()) {
    lines.push(`## ${family}`, "");
    lines.push("| 方法 | 路由 | 策略 | 参数（位置） | CLI |");
    lines.push("| --- | --- | --- | --- | --- |");
    for (const operation of ops) {
      const params = Object.entries(operation.params)
        .map(([name, spec]) => {
          const location = operation.cli.params?.[name] ?? "body";
          return `\`${name}\`(${location}${spec.required ? ",必填" : ""})`;
        })
        .join(" ");
      lines.push(
        `| \`${operation.cli.method} ${operation.cli.path}\` | ${operation.title} | \`${operation.policy}\` | ${params || "—"} | ${operation.cli.command ? `\`superting ${operation.cli.command}\`` : "—"} |`
      );
    }
    lines.push("");
  }

  lines.push(
    "## 错误约定",
    "",
    '- 校验失败：HTTP 400 `{"error":{"code":"validation_error","message":...}}`',
    '- id 不存在：HTTP 404 `{"error":{"code":"not_found",...}}`',
    "- 需要应用窗口的能力：HTTP 503 `renderer_unavailable`（先尝试唤起窗口，仍失败即报错）",
    "- 未认证：HTTP 401；非回环来源：HTTP 403",
    "",
    "## 示例：加一条纠错规则",
    "",
    "```sh",
    "curl -sS -X POST \\",
    '  -H "Authorization: Bearer ${token}" \\',
    '  -H "Content-Type: application/json" \\',
    '  -d \'{"from":"super ting","to":"SuperTing"}\' \\',
    '  "${base_url}/v1/dictionary/aliases"',
    "```",
    "",
    "> 全部机器能力（含 MCP 工具名、参数与使用说明）见 `operations.md`。",
    ""
  );
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const operations = listOperations();
  const outputs = [
    [OUTPUT_PATH, renderOperationsDoc(operations)],
    [ROUTES_PATH, renderRoutesDoc(operations)],
  ];

  if (check) {
    let stale = false;
    for (const [file, rendered] of outputs) {
      const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
      if (existing !== rendered) {
        console.error(
          `[app-operations] ${path.relative(process.cwd(), file)} is out of date — run: node scripts/generate-app-operations-docs.js`
        );
        stale = true;
      }
    }
    if (stale) process.exit(1);
    console.log("[app-operations] generated docs are up to date");
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  for (const [file, rendered] of outputs) {
    fs.writeFileSync(file, rendered);
    console.log(`[app-operations] wrote ${path.relative(process.cwd(), file)}`);
  }
}

if (require.main === module) main();

module.exports = {
  OUTPUT_PATH,
  ROUTES_PATH,
  listOperations,
  renderOperationsDoc,
  renderParamTable,
  renderRoutesDoc,
};
